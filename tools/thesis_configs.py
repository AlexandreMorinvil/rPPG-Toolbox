# ---------------------------------------------------------------- inputs

def load_inputs(thesis_dir=THESIS_DIR):
    with open(thesis_dir / "paths.yaml", encoding="utf-8") as handle:
        setup = yaml.safe_load(handle)
    with open(thesis_dir / "splits.yaml", encoding="utf-8") as handle:
        splits = yaml.safe_load(handle)
    return setup, splits


def lab_folders(splits, split=None, experiment=None):
    """Participant folders of the people of a split (all when None), in one experiment (all when None)."""
    return sorted(session.split("/", 1)[1] for person in splits["lab"]["persons"].values()
                  if split is None or person["split"] == split for session in person["sessions"]
                  if experiment is None or session.split("/", 1)[0].lower() == experiment.lower())


def lab_people(splits, split, experiment):
    """Number of people of a split with sessions in an experiment."""
    return sum(1 for person in splits["lab"]["persons"].values() if person["split"] == split
               and any(session.split("/", 1)[0].lower() == experiment.lower() for session in person["sessions"]))


def person_of_folder(splits):
    """{(experiment, participant folder) lower case: person}."""
    mapping = {}
    for person, entry in splits["lab"]["persons"].items():
        for session in entry["sessions"]:
            experiment, folder = session.split("/", 1)
            mapping[(experiment.lower(), folder.lower())] = person
    return mapping


def literature_path(setup, kind, dataset):
    return (setup.get(kind) or {}).get(dataset) or MISSING.format(key=f"{kind}.{dataset}")


def lab_paths(setup, uv, experiments):
    """(DATA_PATH, EXPERIMENT_PATHS) of the lab data: the video root, or one UV folder per experiment."""
    if not uv:
        return (setup.get("video") or {}).get("lab") or MISSING.format(key="video.lab"), []
    folders = (setup.get("uv") or {}).get("lab") or {}
    entries = [f"{experiment}={folders.get(experiment) or MISSING.format(key='uv.lab.' + experiment)}"
               for experiment in experiments]
    given = ([folders[experiment] for experiment in experiments if folders.get(experiment)]
             or [folder for folder in folders.values() if folder])
    # DATA_PATH must be an existing folder; the experiments themselves come from EXPERIMENT_PATHS.
    return (Path(given[0]).parent.as_posix() if given else MISSING.format(key="uv.lab")), entries


# ---------------------------------------------------------------- config blocks

def data_block(setup, dataset, input_key, prep, role, subjects=None, lab=None):
    """One split's DATA block. lab: {experiments, participants, views} for the vHRM lab data."""
    uv = INPUTS[input_key]["uv"]
    neural = prep is not POS
    block = {"DATASET": "vHRM" if lab else dataset}
    if lab:
        block["DATA_PATH"], experiment_paths = lab_paths(setup, uv, lab["experiments"])
        fs = 30
    else:
        block["DATA_PATH"] = literature_path(setup, "uv" if uv else "video", dataset)
        fs = LITERATURE[dataset]["fs"]
    block.update({"CACHED_PATH": setup["cache"], "DO_PREPROCESS": True, "FS": fs, "BEGIN": 0.0, "END": 1.0})
    if subjects is not None:
        block["SUBJECTS"] = [str(subject) for subject in subjects]
    block["DATA_FORMAT"] = prep["format"]
    block["PREPROCESS"] = {
        "DATA_TYPE": [prep["data_type"]], "LABEL_TYPE": prep["label_type"], "DATA_AUG": ["None"],
        "DO_CHUNK": prep["chunk"] is not None, "CHUNK_LENGTH": prep["chunk"] or 180,
        "RESIZE": {"W": prep["size"], "H": prep["size"]}, "NUM_WORKERS": 2,
        "CROP_FACE": dict(FACE_CROP) if uv is None else {"DO_CROP_FACE": False},
    }
    if uv is not None:
        block["UV"] = {"ENABLED": True, "LAYOUT": "packed", "CHARTS": uv["CHARTS"], "EXCLUDE_CHARTS": uv["EXCLUDE_CHARTS"],
                       "MIN_COVERAGE": 0.25, "FILL": "temporal_mean" if neural else "none",
                       "MIN_PIXEL_VALID_FRACTION": 0.0, "RESAMPLE_TO_FS": False}
    if lab:
        block["VHRM"] = {
            "EXPERIMENTS": list(lab["experiments"]), "EXPERIMENT_PATHS": experiment_paths,
            "PARTICIPANTS": list(lab["participants"]), "EXCLUDE_PARTICIPANTS": [], "LABELS": [],
            "EXCLUDE_LABELS": [], "VIEWS": list(lab["views"]), "CROP_MODE_BY_VIEW": list(CROP_MODES),
            "MIN_FACE_FRACTION": MIN_FACE_FRACTION if uv is None else 0.0,
            "FACE_SEARCH_WIDTH": FACE_SEARCH_WIDTH if uv is None else 1.0,
            "MAX_DURATION_SEC": MAX_DURATION_SEC, "MAX_DURATION_SEC_BY_LABEL": [],
            "PPG_SOURCE": "synthetic", "PPG_DELAY_SEC": 0.0, "LAG_TABLE_PATH": "", "HR_SOURCE": "zephyr",
            "REQUIRE_PPG": role in ("train", "valid"), "VIDEO_DECODER": "auto", "INCREMENTAL_PREPROCESS": True,
            "CACHE_DTYPE": "float16", "SHOW_VIDEO_PROGRESS": True,
        }
        if role == "test" and lab.get("prediction_is_diff") is not None:
            block["VHRM"]["PREDICTION_IS_DIFF"] = lab["prediction_is_diff"]
    return block


def common_blocks(setup, batch, name, description, tags):
    options = setup.get("options") or {}
    return {
        "INFERENCE": {"BATCH_SIZE": 4, "DATA_LOADER_WORKERS": 0, "EVALUATION_METHOD": "FFT",
                      "EVALUATION_WINDOW": {"USE_SMALLER_WINDOW": True, "WINDOW_SIZE": WINDOW_SEC}},
        "VISUALIZE": {"HIGHLIGHTS": True, "HIGHLIGHT_WORST": 3, "VALID_BEST": True, "PROBE_EVERY_N_EPOCHS": 5,
                      "PROBE_COUNT": 6},
        "WANDB": {"ENABLED": bool(options.get("wandb", False)), "MODE": "online", "PROJECT": "rPPG-Toolbox",
                  "ENTITY": "", "RUN_NAME": name, "GROUP": f"thesis-{batch}", "JOB_TYPE": "",
                  "TAGS": ["thesis", batch, *tags], "NOTES": description.splitlines()[0],
                  "LOG_BATCH_LOSS": True, "LOG_FREQ": 50},
    }


def neural_config(setup, batch, name, description, tags, model_key, blocks, mode="train_and_test", init="",
                  model_path="", epochs=EPOCHS, lr=None):
    """A train_and_test (blocks: train, valid, test) or only_test (blocks: test) config of one model."""
    model = MODELS[model_key]
    options = setup.get("options") or {}
    config = {"BASE": [""], "TOOLBOX_MODE": mode, "DESCRIPTION": description,
              "MODEL": {"NAME": model["name"], "DROP_RATE": model["drop"], "RESUME": "", "INIT_WEIGHTS": init,
                        **model["extra"]},
              "LOG": {"PATH": f"{setup['runs']}/{batch_folder(batch)}/{name}"},
              "DEVICE": options.get("device", "cuda:0"), "NUM_OF_GPU_TRAIN": 1}
    if mode == "train_and_test":
        config["TRAIN"] = {"EPOCHS": epochs, "BATCH_SIZE": 4, "LR": lr or model["lr"],
                           "EARLY_STOPPING": {"ENABLED": False, "PATIENCE": 6, "TOLERANCE": 0.0},
                           "MODEL_FILE_NAME": name, "PLOT_LOSSES_AND_LR": True, "DATA_LOADER_WORKERS": 4,
                           "SAVE_RESUME": True, "DATA": blocks["train"]}
        config["VALID"] = {"DATA": blocks["valid"]}
    else:
        config["TRAIN"] = {"DATA_LOADER_WORKERS": 4}
    config["TEST"] = {"DATA": blocks["test"], "METRICS": ["MAE", "RMSE", "MAPE", "Pearson", "SNR", "MACC", "BA"],
                      "USE_LAST_EPOCH": False}
    extra = common_blocks(setup, batch, name, description, tags)
    if model_path:
        extra["INFERENCE"]["MODEL_PATH"] = model_path
    config.update(extra)
    return config


def pos_config(setup, batch, name, description, tags, block):
    options = setup.get("options") or {}
    config = {"BASE": [""], "TOOLBOX_MODE": "unsupervised_method", "DESCRIPTION": description,
              "LOG": {"PATH": f"{setup['runs']}/{batch_folder(batch)}/{name}"},
              "DEVICE": options.get("device", "cuda:0"), "TRAIN": {"DATA_LOADER_WORKERS": 2},
              "UNSUPERVISED": {"METHOD": ["POS"], "METRICS": ["MAE", "RMSE", "MAPE", "Pearson", "SNR"],
                               "DATA": block}}
    config.update(common_blocks(setup, batch, name, description, tags))
    return config


def batch_folder(batch):
    return {"batch1": "batch1_literature", "batch2": "batch2_lab_front", "batch3": "batch3_lab_back"}[batch]


# ---------------------------------------------------------------- the runs

def best_checkpoint(log_path, name):
    """Checkpoint a finished train_and_test run tested (the epoch in its saved_test_outputs), or None."""
    for outputs in sorted(glob.glob(os.path.join(log_path, "*", "saved_test_outputs", f"{name}_outputs.pickle"))):
        try:
            with open(outputs, "rb") as handle:
                epoch = pickle.load(handle).get("meta", {}).get("epoch")
        except Exception:  # an unreadable or partial pickle: treat the run as not finished
            continue
        if epoch is None:
            continue
        found = sorted(glob.glob(os.path.join(log_path, "*", "PreTrainedModels", f"{name}_Epoch{epoch}.pth")))
        if found:
            return found[0].replace("\\", "/")
    return None


def build_runs(setup, splits):
    """{relative config path: config}, and the batch 2 runs whose checkpoint batch 3 still waits for."""
    runs, waiting = {}, []

    # Batch 1: literature datasets, one training per dataset.
    for dataset, info in LITERATURE.items():
        short, subjects = info["short"], splits["literature"][dataset]
        for input_key in BATCH_INPUTS["batch1"]:
            label = INPUTS[input_key]["label"]
            for model_key, model in MODELS.items():
                name = f"b1_{short}_{model_key}_{input_key}"
                blocks = {split: data_block(setup, dataset, input_key, model, split, subjects=subjects[split])
                          for split in SPLITS}
                description = (f"Batch 1 - {model['name']} on {dataset}, {label}.\n"
                               f"Trained on the {len(subjects['train'])} training subjects of thesis/splits.yaml, "
                               f"best epoch on the {len(subjects['valid'])} validation subjects, tested on the "
                               f"{len(subjects['test'])} test subjects.")
                runs[f"batch1_literature/{short}/{model_key}_{input_key}.yaml"] = neural_config(
                    setup, "batch1", name, description, [short, model_key, input_key], model_key, blocks)
            name = f"b1_{short}_pos_{input_key}"
            description = (f"Batch 1 - POS on {dataset}, {label}, every subject (the test subjects are a subset: "
                           f"see thesis/splits.yaml).")
            runs[f"batch1_literature/{short}/pos_{input_key}.yaml"] = pos_config(
                setup, "batch1", name, description, [short, "pos", input_key],
                data_block(setup, dataset, input_key, POS, "test"))

    # Batch 2: lab data, front camera, one training per experiment, model and input.
    for experiment in LAB_EXPERIMENTS["batch2"]:
        persons = {split: lab_folders(splits, split, experiment) for split in SPLITS}
        people = {split: lab_people(splits, split, experiment) for split in SPLITS}
        short = experiment.lower()
        lab2 = {"experiments": [experiment], "views": ["front"]}
        for input_key in BATCH_INPUTS["batch2"]:
            label = INPUTS[input_key]["label"]
            for model_key, model in MODELS.items():
                name = f"b2_{short}_{model_key}_{input_key}"
                blocks = {split: data_block(setup, "lab", input_key, model, split,
                                            lab={**lab2, "participants": persons[split]}) for split in SPLITS}
                description = (f"Batch 2 - {model['name']} on {experiment}, front camera, {label}.\n"
                               f"Trained on the {people['train']} training people of thesis/splits.yaml, best epoch "
                               f"on the {people['valid']} validation people, tested on the {people['test']} test "
                               f"people. First {MAX_DURATION_SEC:g} s of each recording.")
                runs[f"batch2_lab_front/{experiment}/{model_key}_{input_key}.yaml"] = neural_config(
                    setup, "batch2", name, description, [experiment, "front", model_key, input_key], model_key,
                    blocks)
            name = f"b2_{short}_pos_{input_key}"
            description = (f"Batch 2 - POS on {experiment}, front camera, {label}, every participant. First "
                           f"{MAX_DURATION_SEC:g} s of each recording.")
            runs[f"batch2_lab_front/{experiment}/pos_{input_key}.yaml"] = pos_config(
                setup, "batch2", name, description, [experiment, "front", "pos", input_key],
                data_block(setup, "lab", input_key, POS, "test", lab={**lab2, "participants": []}))

    # Batch 3: lab data, back cameras, one fine-tuning per experiment from its batch 2 model.
    back, views = ["back-left", "back-right"], ["front", "back-left", "back-right"]
    for experiment in LAB_EXPERIMENTS["batch3"]:
        persons = {split: lab_folders(splits, split, experiment) for split in SPLITS}
        short = experiment.lower()
        for input_key in BATCH_INPUTS["batch2"]:
            label = INPUTS[input_key]["label"]
            for model_key, model in MODELS.items():
                source = f"b2_{short}_{model_key}_{input_key}"
                checkpoint = best_checkpoint(f"{setup['runs']}/{batch_folder('batch2')}/{source}", source)
                if checkpoint is None:
                    waiting.append(source)
                    checkpoint = (f"<run batch2_lab_front/{experiment}/{model_key}_{input_key}.yaml, "
                                  f"then tools/thesis_configs.py>")
                is_diff = model["label_type"] == "DiffNormalized"
                name = f"b3_{short}_ft_{model_key}_{input_key}"
                blocks = {split: data_block(setup, "lab", input_key, model, split, lab={
                    "experiments": [experiment], "participants": persons[split],
                    "views": views if split == "test" else back}) for split in SPLITS}
                description = (f"Batch 3 - {model['name']} on {experiment}, {label}: the batch 2 front-camera model "
                               f"of {experiment} fine-tuned on the back-left + back-right videos of the training "
                               f"people, best epoch on the validation people, tested on the three views of the test "
                               f"people (by_view.csv).\n"
                               f"{FINETUNE['epochs']} epochs at {FINETUNE['lr_factor']:g} x the learning rate.")
                runs[f"batch3_lab_back/{experiment}/finetune/{model_key}_{input_key}.yaml"] = neural_config(
                    setup, "batch3", name, description, [experiment, "back", "finetune", model_key, input_key],
                    model_key, blocks, init=checkpoint, epochs=FINETUNE["epochs"],
                    lr=model["lr"] * FINETUNE["lr_factor"])
                name = f"b3_{short}_zs_{model_key}_{input_key}"
                test = data_block(setup, "lab", input_key, model, "test", lab={
                    "experiments": [experiment], "participants": persons["test"], "views": views,
                    "prediction_is_diff": is_diff})
                description = (f"Batch 3 - {model['name']} on {experiment}, {label}: the batch 2 front-camera model "
                               f"of {experiment} tested as it is on the three views of the test people (by_view.csv), "
                               f"the reference for the fine-tuned model.")
                runs[f"batch3_lab_back/{experiment}/zeroshot/{model_key}_{input_key}.yaml"] = neural_config(
                    setup, "batch3", name, description, [experiment, "back", "zeroshot", model_key, input_key],
                    model_key, {"test": test}, mode="only_test", model_path=checkpoint)
            name = f"b3_{short}_pos_{input_key}"
            description = (f"Batch 3 - POS on {experiment}, back-left and back-right cameras, {label}, every "
                           f"participant (batch 2 has the front camera).")
            runs[f"batch3_lab_back/{experiment}/pos_{input_key}.yaml"] = pos_config(
                setup, "batch3", name, description, [experiment, "back", "pos", input_key],
                data_block(setup, "lab", input_key, POS, "test", lab={
                    "experiments": [experiment], "participants": [], "views": back}))
    return runs, waiting


class _ConfigDumper(yaml.SafeDumper):
    """The layout of the hand-written configs: block mappings, flow lists, '|' for multi-line text, no anchors."""

    def ignore_aliases(self, data):
        return True


_ConfigDumper.add_representer(dict, lambda dumper, value: dumper.represent_mapping(
    "tag:yaml.org,2002:map", value, flow_style=False))
_ConfigDumper.add_representer(list, lambda dumper, value: dumper.represent_sequence(
    "tag:yaml.org,2002:seq", value, flow_style=True))
_ConfigDumper.add_representer(str, lambda dumper, value: dumper.represent_scalar(
    "tag:yaml.org,2002:str", value, style="|" if "\n" in value else None))


def dump_config(config):
    return HEADER + yaml.dump(config, Dumper=_ConfigDumper, sort_keys=False, width=120, allow_unicode=True)


def write_runs(runs, output_dir=OUTPUT_DIR):
    output_dir = Path(output_dir)
    written = set()
    for relative, config in runs.items():
        path = output_dir / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        text = dump_config(config)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
        written.add(path.resolve())
    removed = 0
    for path in output_dir.rglob("*.yaml"):
        if path.resolve() not in written and path.read_text(encoding="utf-8").startswith(HEADER):
            path.unlink()
            removed += 1
    return removed


# ---------------------------------------------------------------- checks

def _exists(path):
    return bool(path) and not str(path).startswith("<") and os.path.isdir(path)


def literature_subjects(dataset, folder):
    """Subjects present in a literature dataset folder (raw or converted)."""
    from cache_naming import subject_key
    names = os.listdir(folder)
    if dataset == "UBFC-rPPG":
        return {subject_key(name) for name in names if name.startswith("subject")}
    if dataset == "PURE":
        return {subject_key(name[:2]) for name in names if name[:2].isdigit() and name[2:3] == "-"}
    return {subject_key(name) for name in names if name.isdigit()}


def check_inputs(setup, splits):
    """Problems of the inputs: (errors, warnings)."""
    from cache_naming import subject_key
    errors, warnings = [], []
    split_values = {person: entry.get("split") for person, entry in splits["lab"]["persons"].items()}
    for person, split in split_values.items():
        if split not in SPLITS:
            errors.append(f"lab person {person}: split must be one of {SPLITS}, not {split!r}")
    owners = {}
    for person, entry in splits["lab"]["persons"].items():
        for session in entry["sessions"]:
            if "/" not in session:
                errors.append(f"lab person {person}: session {session!r} must be <experiment>/<participant folder>")
            if session.lower() in owners:
                errors.append(f"lab session {session} belongs to {owners[session.lower()]} and {person}")
            owners[session.lower()] = person

    video_lab = (setup.get("video") or {}).get("lab")
    uv_lab = (setup.get("uv") or {}).get("lab") or {}
    if not _exists(video_lab):
        warnings.append(f"video.lab not found: {video_lab or '(empty)'}")
    else:
        for session in owners:
            experiment, folder = session.split("/", 1)
            matches = [entry for entry in os.listdir(video_lab) if entry.lower() == experiment]
            if not matches or not any(entry.lower() == folder for entry in os.listdir(os.path.join(video_lab, matches[0]))):
                warnings.append(f"lab session {session} ({owners[session]}) is not in {video_lab}")
        for experiment in LAB_EXPERIMENTS["batch2"]:
            experiment_dir = next((os.path.join(video_lab, entry) for entry in os.listdir(video_lab)
                                   if entry.lower() == experiment.lower()), None)
            if experiment_dir is None:
                warnings.append(f"no {experiment} folder in {video_lab}")
                continue
            for folder in sorted(os.listdir(experiment_dir)):
                if os.path.isdir(os.path.join(experiment_dir, folder, "labelled_segments")) \
                        and f"{experiment.lower()}/{folder.lower()}" not in owners:
                    warnings.append(f"{experiment}/{folder} is in no split (add it to a person in thesis/splits.yaml)")
    for experiment in LAB_EXPERIMENTS["batch2"]:
        folder = uv_lab.get(experiment)
        if not _exists(folder):
            warnings.append(f"uv.lab.{experiment} not found: {folder or '(empty)'} - the UV configs of {experiment} "
                            f"cannot run")
            continue
        present = {entry.lower() for entry in os.listdir(folder)}
        missing = sorted(session.split("/", 1)[1] for session in owners
                         if session.split("/", 1)[0] == experiment.lower() and session.split("/", 1)[1] not in present)
        if missing:
            warnings.append(f"uv.lab.{experiment}: {len(missing)} participant folders missing ({', '.join(missing)})")

    for dataset in LITERATURE:
        lists = splits["literature"][dataset]
        keys = {split: [subject_key(subject) for subject in lists.get(split, [])] for split in SPLITS}
        for first in SPLITS:
            for second in SPLITS:
                if first < second and set(keys[first]) & set(keys[second]):
                    errors.append(f"{dataset}: subjects in {first} and {second}: "
                                  f"{sorted(set(keys[first]) & set(keys[second]))}")
        for kind in ("video", "uv"):
            folder = (setup.get(kind) or {}).get(dataset)
            if not _exists(folder):
                warnings.append(f"{kind}.{dataset} not found: {folder or '(empty)'}")
                continue
            present = literature_subjects(dataset, folder)
            listed = set().union(*map(set, keys.values()))
            if listed - present:
                warnings.append(f"{kind}.{dataset}: listed subjects missing in {folder}: {sorted(listed - present)}")
            if present - listed:
                warnings.append(f"{kind}.{dataset}: subjects in no split: {sorted(present - listed, key=int)}")
    return errors, warnings


# ---------------------------------------------------------------- finding the datasets

SKIP_DIRS = {"$recycle.bin", "system volume information", "windows", "program files", "program files (x86)",
             "programdata", "appdata", "node_modules", ".git", "labelled_segments", "synthetic_ppg", "__pycache__"}


def _first(folder, pattern):
    return next(iter(Path(folder).glob(pattern)), None) is not None


SIGNATURES = {
    ("video", "UBFC-rPPG"): lambda folder: _first(folder, "subject*/vid.avi"),
    ("uv", "UBFC-rPPG"): lambda folder: _first(folder, "subject*/vid_skin_uv.h5"),
    ("video", "PURE"): lambda folder: (_first(folder, "[0-9][0-9]-[0-9][0-9]/*.png")
                                       or _first(folder, "[0-9][0-9]-[0-9][0-9]/[0-9][0-9]-[0-9][0-9]/*.png")),
    ("uv", "PURE"): lambda folder: (_first(folder, "[0-9][0-9]-[0-9][0-9]_skin_uv.h5")
                                    or _first(folder, "[0-9][0-9]-[0-9][0-9]/[0-9][0-9]-[0-9][0-9]_skin_uv.h5")),
    ("video", "COHFACE"): lambda folder: _first(folder, "[0-9]*/0/data.avi"),
    ("uv", "COHFACE"): lambda folder: _first(folder, "[0-9]*/0/data_skin_uv.h5"),
}


def _lab_video_root(folder):
    for entry in os.scandir(folder):
        if entry.is_dir() and entry.name.lower() in {e.lower() for e in LAB_EXPERIMENTS["batch2"]} \
                and _first(entry.path, "*/labelled_segments/*/cam*_Camera_*.mp4"):
            return True
    return False


def _uv_experiment_files(folder):
    return len(glob.glob(os.path.join(folder, "*", "labelled_segments", "*", "cam*_skin_uv.h5")))


def search_roots():
    if os.name == "nt":
        return [f"{letter}:/" for letter in string.ascii_uppercase if os.path.isdir(f"{letter}:/")]
    return ["/"]


def find_paths(roots, max_depth=5, skip=()):
    """{(kind, dataset): [folders]} and {experiment: [(h5 count, folder)]} found under the roots."""
    found, experiments = {}, {}
    skip = {os.path.normcase(os.path.abspath(path)) for path in skip}
    names = {experiment.lower(): experiment for experiment in LAB_EXPERIMENTS["batch2"]}
    for root in roots:
        root_depth = os.path.abspath(root).rstrip("\\/").count(os.sep)
        for folder, subfolders, _ in os.walk(root):
            depth = os.path.abspath(folder).rstrip("\\/").count(os.sep) - root_depth
            subfolders[:] = [name for name in subfolders if name.lower() not in SKIP_DIRS
                             and os.path.normcase(os.path.abspath(os.path.join(folder, name))) not in skip]
            if depth >= max_depth:
                subfolders[:] = []
            try:
                for key, signature in SIGNATURES.items():
                    if signature(folder):
                        found.setdefault(key, []).append(folder)
                if _lab_video_root(folder):
                    found.setdefault(("video", "lab"), []).append(folder)
                name = os.path.basename(os.path.normpath(folder)).lower()
                if name in names:
                    count = _uv_experiment_files(folder)
                    if count:
                        experiments.setdefault(names[name], []).append((count, folder))
            except OSError:
                continue
    return found, experiments


PATHS_TEMPLATE = """# Where the thesis datasets are, and where runs and caches go (tools/thesis_configs.py reads it).
# After moving a drive: python tools/thesis_configs.py --find-paths   (fills the entries it can find, keeps the rest)
# then:                 python tools/thesis_configs.py                (writes every config again)

cache: {cache}            # preprocessing caches (shared by every run)
runs: {runs}                        # LOG.PATH root: <runs>/<batch>/<run name>

# Face crop input: the original videos.
video:
  UBFC-rPPG: {video_ubfc}
  PURE: {video_pure}
  COHFACE: {video_cohface}
  lab: {video_lab}              # holds baseline/, JZC/ and RM/

# UV input: the vHRM Studio conversions (mirror mode).
uv:
  UBFC-rPPG: {uv_ubfc}
  PURE: {uv_pure}
  COHFACE: {uv_cohface}
  lab:                                      # one folder per experiment (they need not share a parent)
    baseline: {uv_baseline}
    JZC: {uv_jzc}
    RM: {uv_rm}

options:
  device: {device}
  wandb: {wandb}                               # Weights & Biases logging (WANDB.ENABLED)
"""


def write_paths(setup, path):
    def value(item):
        return yaml.safe_dump(item if item is not None else "", default_flow_style=True).strip().removesuffix("...").strip()

    video, uv, options = setup.get("video") or {}, setup.get("uv") or {}, setup.get("options") or {}
    lab = uv.get("lab") or {}
    text = PATHS_TEMPLATE.format(
        cache=value(setup.get("cache")), runs=value(setup.get("runs")),
        video_ubfc=value(video.get("UBFC-rPPG")), video_pure=value(video.get("PURE")),
        video_cohface=value(video.get("COHFACE")), video_lab=value(video.get("lab")),
        uv_ubfc=value(uv.get("UBFC-rPPG")), uv_pure=value(uv.get("PURE")), uv_cohface=value(uv.get("COHFACE")),
        uv_baseline=value(lab.get("baseline")), uv_jzc=value(lab.get("JZC")), uv_rm=value(lab.get("RM")),
        device=value(options.get("device", "cuda:0")), wandb=value(bool(options.get("wandb", True))))
    Path(path).write_text(text, encoding="utf-8")


def update_paths(setup, found, experiments):
    """Fill the entries that are empty or point to a missing folder; return the changes."""
    changes = []
    for (kind, dataset), folders in sorted(found.items()):
        section = setup.setdefault(kind, {})
        if not _exists(section.get(dataset)):
            section[dataset] = folders[0].replace("\\", "/")
            changes.append(f"{kind}.{dataset} = {section[dataset]}" + (f" (also: {folders[1:]})" if folders[1:] else ""))
    lab = setup.setdefault("uv", {}).setdefault("lab", {})
    for experiment, candidates in sorted(experiments.items()):
        if not _exists(lab.get(experiment)):
            count, folder = max(candidates)
            lab[experiment] = folder.replace("\\", "/")
            others = [f"{other} ({n} files)" for n, other in sorted(candidates, reverse=True) if other != folder]
            changes.append(f"uv.lab.{experiment} = {lab[experiment]} ({count} files)"
                           + (f"; also: {others}" if others else ""))
    return changes


