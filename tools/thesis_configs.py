"""Configs of the thesis experiments, written from thesis/paths.yaml and thesis/splits.yaml.

    python tools/thesis_configs.py                # check the inputs, write configs/launcher/thesis/
    python tools/thesis_configs.py --check        # check only: missing folders, split problems
    python tools/thesis_configs.py --find-paths   # search the drives for the datasets, update thesis/paths.yaml

Batches (inputs: face = face crop; uvhead / uvbody / uvfull = UV map of the head / everything but the head / the
whole body; POS runs on every participant, the neural models train on the training split):

    batch1_literature/<dataset>/   UBFC-rPPG, PURE, COHFACE. PhysNet, FactorizePhys, RhythmFormer x face, uvhead,
                                   uvfull (one training per dataset), and POS.
    batch2_lab_front/<experiment>/ baseline, JZC, RM separately, front camera. Models x face, uvhead, uvbody, uvfull
                                   (one training per experiment), and POS.
    batch3_lab_back/<experiment>/  baseline, JZC separately, back cameras. finetune/: the experiment's batch 2 model
                                   fine-tuned on its back-left + back-right videos of the training people, tested on the
                                   three views; zeroshot/: the batch 2 model tested on the three views as it is; POS on
                                   the back views (batch 2 has the front).

Batch 3 starts from the batch 2 checkpoints: run batch 2, then run this script again. It reads the epoch each batch 2
run tested (its saved_test_outputs) and writes that checkpoint into MODEL.INIT_WEIGHTS / INFERENCE.MODEL_PATH.
Generated files start with a header line; files with that header that are no longer generated are removed.
"""

